//! Every public DBC catalog loader against the installed 3.3.5 data. A 2026-10-23 audit compared
//! each loader's schema, after the build-12340 column map, with WoWDBDefs' 3.3.5.12340 layouts
//! (string, float and integer columns) and checked the installed string offsets and floats; it
//! found no mismatch. This sweep keeps every loader loading the shipped files.

macro_rules! failures {
    ($chain:expr; $($loader:path),* $(,)?) => {{
        let mut failed = Vec::new();
        $(
            if let Err(e) = $loader(&mut $chain) {
                failed.push(format!("{}: {e:#}", stringify!($loader)));
            }
        )*
        failed
    }};
}

